function montarEventos(): GroupEvent[] {
  const lista: GroupEvent[] = []
  for (const [area, itens] of SECOES) {
    for (const [code, label, proprio] of itens) {
      const key = proprio || (code ? `wm10.${code}` : label)
      lista.push({
        code,
        key,
        label,
        area,
        padrao: "bloquear",
      })
    }
  }
  return lista
}

export const GROUP_EVENTS = montarEventos()

export const GROUP_EVENT_AREAS = [...new Set(GROUP_EVENTS.map((event) => event.area))]

export function regraDoEvento(salvo: unknown, event: GroupEvent) {
  const value = salvo && typeof salvo === "object" ? String((salvo as Record<string, unknown>)[event.key] || "") : ""
  if (value === "permitir" || value === "bloquear") return value
  return event.padrao
}

export function eventoPermitido(salvo: unknown, key: string) {
  const event = GROUP_EVENTS.find((item) => item.key === key)
  if (!event) return false
  return regraDoEvento(salvo, event) === "permitir"
}
